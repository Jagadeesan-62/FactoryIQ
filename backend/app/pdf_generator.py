class NumberedCanvas(canvas.Canvas):
    """Canvas class to generate 'Page X of Y' page numbers dynamically."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            super().showPage()
        super().save()

    def draw_page_number(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 9)
        self.setFillColor(colors.HexColor("#64748B"))
        
        # Draw a thin footer separator line
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(54, 50, 612 - 54, 50)
        
        # Draw page numbers right-aligned, and system tag left-aligned
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(612 - 54, 38, page_text)
        self.drawString(54, 38, "FactoryIQ AI Operations Analytics — Confidential")
        self.restoreState()


def parse_report_to_sections(report_text: str) -> list[tuple[str, str]]:
    """Parses raw report text into section headers and paragraphs."""
    sections = []
    headers = [
        "Production Summary",
        "Prediction",
        "Confidence",
        "Key Factors",
        "Production Insights",
        "Risk Analysis",
        "Energy Analysis",
        "Machine Utilization Analysis",
        "Recommendations",
        "Conclusion"
    ]
    
    positions = []
    for h in headers:
        pattern = re.compile(rf"(?:^|\n)[#*\s]*{re.escape(h)}[#*\s:]*(?:\n|$)", re.IGNORECASE)
        match = pattern.search(report_text)
        if match:
            positions.append((match.start(), match.end(), h))
            
    positions.sort(key=lambda x: x[0])
    
    if not positions:
        return [("Report Details", report_text)]
        
    for i in range(len(positions)):
        start_idx = positions[i][1]
        end_idx = positions[i+1][0] if i + 1 < len(positions) else len(report_text)
        header_name = positions[i][2]
        content = report_text[start_idx:end_idx].strip()
        
        # Strip local fallback notice if present
        if "[Generated by local fallback" in content:
            content = content.split("[Generated by local fallback")[0].strip()
            
        if content:
            # Clean up residual markdown formatting in the paragraph text
            content = re.sub(r"\*\*|#", "", content)
            sections.append((header_name, content))
            
    return sections


def generate_pdf_report(record) -> io.BytesIO:
    """Generates a styled PDF report for a PredictionHistory record."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=54,
        leftMargin=54,
        topMargin=54,
        bottomMargin=72
    )
    
    styles = getSampleStyleSheet()
    
    # Custom Palette
    primary_color = colors.HexColor("#1E3A8A")   # Navy
    secondary_color = colors.HexColor("#0D9488") # Teal
    dark_neutral = colors.HexColor("#1E293B")    # Charcoal
    light_neutral = colors.HexColor("#F8FAFC")   # Slate 50
    border_color = colors.HexColor("#E2E8F0")    # Slate 200
    
    # Custom Paragraph Styles
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Title"],
        fontName="Helvetica-Bold",
        fontSize=24,
        leading=28,
        textColor=primary_color,
        alignment=0,
        spaceAfter=6
    )
    
    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=11,
        leading=14,
        textColor=colors.HexColor("#64748B"),
        spaceAfter=20
    )
    
    h2_style = ParagraphStyle(
        "DocH2",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=16,
        textColor=primary_color,
        spaceBefore=14,
        spaceAfter=6,
        keepWithNext=True
    )
    
    body_style = ParagraphStyle(
        "DocBody",
        parent=styles["BodyText"],
        fontName="Helvetica",
        fontSize=9.5,
        leading=14,
        textColor=dark_neutral,
        spaceAfter=10
    )
    
    table_label_style = ParagraphStyle(
        "TableLabel",
        fontName="Helvetica-Bold",
        fontSize=9,
        leading=11,
        textColor=primary_color
    )
    
    table_val_style = ParagraphStyle(
        "TableVal",
        fontName="Helvetica",
        fontSize=9,
        leading=11,
        textColor=dark_neutral
    )
    
    story = []
    
    # --- Header Banner ---
    mapping = get_industry_mapping(getattr(record.user, 'industry', '🚗 Automotive'))
    labels = mapping["labels"]
    
    story.append(Paragraph("FactoryIQ AI", title_style))
    story.append(Paragraph(mapping["pdf_title"], subtitle_style))
    
    # --- Metadata & Model Verdict Table ---
    created_str = record.created_at.strftime("%Y-%m-%d %H:%M:%S UTC")
    
    meta_data = [
        [
            Paragraph("Report Date:", table_label_style), Paragraph(created_str, table_val_style),
            Paragraph("Efficiency Class:", table_label_style), Paragraph(f"<b>{record.prediction}</b>", table_val_style)
        ],
        [
            Paragraph("Record ID:", table_label_style), Paragraph(f"#{record.id}", table_val_style),
            Paragraph("Model Confidence:", table_label_style), Paragraph(f"{record.confidence:.2f}%" if record.confidence else "N/A", table_val_style)
        ]
    ]
    
    meta_table = Table(meta_data, colWidths=[90, 160, 110, 144])
    meta_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), light_neutral),
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ('PADDING', (0,0), (-1,-1), 8),
        ('LINEBELOW', (0,0), (-1,-1), 0.5, border_color),
        ('BOX', (0,0), (-1,-1), 1, primary_color),
    ]))
    story.append(meta_table)
    story.append(Spacer(1, 15))
    
    # --- Operational Inputs Grid ---
    story.append(Paragraph("Operational Input Parameters", h2_style))
    
    input_data = [
        [
            Paragraph(labels["production_time"], table_label_style), Paragraph(f"{record.production_time:.1f}", table_val_style),
            Paragraph(labels["machine_utilization"], table_label_style), Paragraph(f"{record.machine_utilization:.1f}", table_val_style),
            Paragraph(labels["energy_consumption"], table_label_style), Paragraph(f"{record.energy_consumption:.1f}", table_val_style)
        ],
        [
            Paragraph(labels["material_usage"], table_label_style), Paragraph(f"{record.material_usage:.1f}", table_val_style),
            Paragraph(labels["downtime"], table_label_style), Paragraph(f"{record.downtime:.1f}", table_val_style),
            Paragraph(labels["worker_count"], table_label_style), Paragraph(f"{int(record.worker_count)}", table_val_style)
        ],
        [
            Paragraph(labels["defect_rate"], table_label_style), Paragraph(f"{record.defect_rate:.2f}", table_val_style),
            Paragraph(labels["maintenance_frequency"], table_label_style), Paragraph(f"{int(record.maintenance_frequency)}", table_val_style),
            Paragraph(labels["inventory_level"], table_label_style), Paragraph(f"{int(record.inventory_level)}", table_val_style)
        ]
    ]
    
    input_table = Table(input_data, colWidths=[110, 58, 120, 58, 110, 48])
    input_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), colors.white),
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ('PADDING', (0,0), (-1,-1), 6),
        ('INNERGRID', (0,0), (-1,-1), 0.5, border_color),
        ('BOX', (0,0), (-1,-1), 0.5, border_color),
    ]))
    story.append(input_table)
    story.append(Spacer(1, 15))
    
    # --- Report Text Content ---
    story.append(Paragraph("Detailed Performance Analysis", h2_style))
    
    raw_report = record.report or "No report content generated for this record."
    sections = parse_report_to_sections(raw_report)
    
    for sec_title, sec_content in sections:
        # Avoid redundant section header for Prediction/Confidence since it's in the top table
        if sec_title in ["Prediction", "Confidence"]:
            continue
        story.append(Paragraph(sec_title, h2_style))
        story.append(Paragraph(sec_content, body_style))
        
    doc.build(story, canvasmaker=NumberedCanvas)
    buffer.seek(0)
    return buffer
